# =============================================================================
def standardize_columns(df, is_new_format=False):
    """Standardize column names across old and new formats"""
    if is_new_format:
        # New CM-UDiFF format columns
        col_mapping = {
            'TckrSymb': 'Stock',
            'SctySrs': 'Series',
            'OpnPric': 'Open',
            'HghPric': 'High',
            'LwPric': 'Low',
            'ClsPric': 'Close',
            'LastPric': 'Last',
            'PrvsClsgPric': 'Prev_Close',
            'TtlTradgVol': 'Volume',
            'TtlTrfVal': 'Turnover',
            'TradDt': 'Date'
        }
    else:
        # Old CM-Bhavcopy format columns
        col_mapping = {
            'SYMBOL': 'Stock',
            'SERIES': 'Series',
            'OPEN': 'Open',
            'HIGH': 'High',
            'LOW': 'Low',
            'CLOSE': 'Close',
            'LAST': 'Last',
            'PREVCLOSE': 'Prev_Close',
            'TOTTRDQTY': 'Volume',
            'TOTTRDVAL': 'Turnover',
            'TIMESTAMP': 'Date'
        }

    df = df.rename(columns=col_mapping)
    return df

