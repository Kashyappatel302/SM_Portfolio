# =============================================================================
def fetch_all_data(start_date, end_date, nifty500_symbols):
    """Fetch all bhavcopy data for date range"""
    all_data = []
    current_date = start_date
    total_days = (end_date - start_date).days
    success_count = 0
    session = get_nse_session()

    print(f"\nDownloading data from {start_date.date()} to {end_date.date()}...")
    print(f"Format switch date: {FORMAT_SWITCH_DATE.date()} (Old→CM-UDiFF)")
    print("-" * 60)

    while current_date <= end_date:
        if current_date.weekday() < 5:  # Skip weekends
            df = download_bhavcopy(current_date, session)

            if df is not None and len(df) > 0:
                is_new = current_date >= FORMAT_SWITCH_DATE
                df = standardize_columns(df, is_new_format=is_new)

                # Filter to EQ series
                if 'Series' in df.columns:
                    df = df[df['Series'].isin(['EQ', 'EQ '])]

                # Filter to NIFTY 500 stocks
                if 'Stock' in df.columns:
                    df['Stock'] = df['Stock'].astype(str).str.upper().str.strip()
                    df = df[df['Stock'].isin(nifty500_symbols)]

                if len(df) > 0:
                    df['Date'] = current_date
                    all_data.append(df)
                    success_count += 1

                    if success_count % 100 == 0:
                        pct = (current_date - start_date).days / total_days * 100
                        fmt = "NEW" if is_new else "OLD"
                        print(f"[{success_count} days] {pct:.1f}% | {current_date.date()} ({fmt})")

            time.sleep(0.5)  # Rate limiting

        current_date += timedelta(days=1)

    print("-" * 60)
    print(f"Downloaded {success_count} trading days")

    return pd.concat(all_data, ignore_index=True) if all_data else None

