# DOWNLOAD OLD FORMAT (Before July 8, 2024) - Using jugaad-data
# =============================================================================
def download_old_format(dt, session=None):
    """Download old CM-Bhavcopy format using jugaad-data style URL"""
    dd = dt.strftime('%d')
    MMM = dt.strftime('%b').upper()
    yyyy = dt.year

    url = f"https://nsearchives.nseindia.com/content/historical/EQUITIES/{yyyy}/{MMM}/cm{dd}{MMM}{yyyy}bhav.csv.zip"

    if session is None:
        session = get_nse_session()

    for attempt in range(RETRY_COUNT):
        try:
            resp = session.get(url, timeout=30)
            if resp.status_code == 200:
                with ZipFile(BytesIO(resp.content)) as z:
                    csv_name = z.namelist()[0]
                    df = pd.read_csv(z.open(csv_name))
                    return df
            elif resp.status_code == 404:
                return None
        except Exception:
            if attempt < RETRY_COUNT - 1:
                time.sleep(RETRY_DELAY)
    return None

# =============================================================================
# DOWNLOAD NEW FORMAT (July 8, 2024 onwards) - CM-UDiFF
# =============================================================================
def download_new_format(dt, session=None):
    """
    Download new CM-UDiFF Common Bhavcopy Final format
    URL: https://nsearchives.nseindia.com/content/cm/BhavCopy_NSE_CM_0_0_0_{YYYYMMDD}_F_0000.csv.zip
    """
    date_str = dt.strftime('%Y%m%d')
    url = f"https://nsearchives.nseindia.com/content/cm/BhavCopy_NSE_CM_0_0_0_{date_str}_F_0000.csv.zip"

    if session is None:
        session = get_nse_session()

    for attempt in range(RETRY_COUNT):
        try:
            resp = session.get(url, timeout=30)
            if resp.status_code == 200:
                with ZipFile(BytesIO(resp.content)) as z:
                    csv_name = z.namelist()[0]
                    df = pd.read_csv(z.open(csv_name))
                    return df
            elif resp.status_code == 404:
                return None
        except Exception:
            if attempt < RETRY_COUNT - 1:
                time.sleep(RETRY_DELAY)
    return None

