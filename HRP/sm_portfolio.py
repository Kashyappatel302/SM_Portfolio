# UNIFIED DOWNLOAD FUNCTION
# =============================================================================
def download_bhavcopy(dt, session=None):
    """Download bhavcopy using appropriate format based on date"""
    if dt >= FORMAT_SWITCH_DATE:
        return download_new_format(dt, session)
    else:
        return download_old_format(dt, session)

